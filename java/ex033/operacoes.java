public class operacoes {

    public static int soma (int a, int b) {
        int s = a + b;
        return s;
    }

    public static int subtracao (int a, int b) {
        int s = a - b;
        return s;
    }

    public static int multiplicacao (int a, int b) {
        int s = a * b;
        return s;
    }

    public static double divisao (double a, double b) {
        double s = a / b;
        return s;
    }
}