# Conceito - Concatenação de Strings

n1 = input('Digite algo: ')


print(n1.isalpha())  # letras

print(n1.isalnum())  # Números, mas não impede de escrever *letras e números juntos*

print(n1.isascii())  # ASCII: caracteres simples -> não inclui acentos, emojis, caracteres especiais

print(n1.isdecimal())  # Números inteiros - 1 a 9

print(n1.isdigit())  # Digitos comuns e Números inteiros - 1 a 9

print(n1.isidentifier())  # Nome válido para uma variável 

print(n1.islower())  # letras minúsculas

print(n1.isnumeric())  # Qualquer número

print(n1.isprintable())  # Apenas o que pode ser impresso na tela

print(n1.isupper())  # letras maiúsculas

print(n1.isspace())  # Apenas espaço ()

print(n1.istitle())  # Formato De Título
